class Link(httpx.BaseTransport):
    """Throttled link that can be cut: sleeps len(bytes)/rate for each request and response."""
    def __init__(self, rate=None):
        self.inner, self.rate, self.down, self.sent, self.received = httpx.HTTPTransport(), rate, False, 0, 0

    def handle_request(self, req):
        if self.down:
            raise httpx.ConnectError("offline", request=req)
        body = req.read()
        self.sent += len(body)
        if self.rate:
            time.sleep(len(body) / self.rate)
        resp = self.inner.handle_request(req)
        data = resp.read()
        self.received += len(data)
        if self.rate:
            time.sleep(len(data) / self.rate)
        return httpx.Response(resp.status_code, headers=resp.headers, content=data, request=req)


